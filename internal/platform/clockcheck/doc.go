// Package clockcheck 检查进程看到的日期有没有突然跳动。
//
// 每秒读取一次日期，并同时记录单调计时。单调计时只计算经过多久，不跟随
// 校时改变。两者增量相差很大，才说明日期被拨动；任务晚一点得到 CPU，
// 会让两者一起变长，不该被当成校时问题。超过 100 毫秒的差值才中止检查。
//
// 文件清单：
//   - doc.go：解释为什么需要同时读两种时间。
//   - sample.go：输出六十次采样，并严格检查样本和时间增量。
//   - sample_test.go：验证前跳、回拨、边界、采样延迟与取消。
//
// 阅读顺序：Sample → Check。采样器可以在容器内独立运行，不连接数据库或模型。
