// Package resilience 提供三种服务治理手段：限流、重试和熔断。它们都和业务无关，可以给任何调用使用。
//
// 三者解决的问题不同：
//   - 限流：限制每秒最多处理多少个请求。超出的请求直接返回 429，而不是在入口无限排队，
//     把服务拖垮。用的是令牌桶算法：每秒往桶里放固定数量的令牌，请求拿到令牌才能进入。
//   - 重试：调用失败后再试一次。但只有调用方明确说“这个错误可以重试”时才重试，并且有次数和时间的上限，
//     每次重试前等待的时间逐次加倍（指数退避）。
//   - 熔断：下游持续出错时，暂时不再调用它，直接返回失败。像电路里的保险丝：
//     先断开，过一会儿放一个请求试探，成功了再恢复。这样不会让大量请求堵在一个已经坏掉的服务上。
//
// 谁调用它：订单服务的 HTTP 入口用限流；inventoryclient 调用库存服务时用重试和熔断。
// 哪些错误值得重试、哪些算熔断里的“失败”，由调用方决定，本包不认识商品或订单。
//
// 文件清单：
//   - doc.go：本说明。
//   - http.go：HTTP 限流中间件，以及给每个请求设置总时限的中间件。
//   - retry.go：带上限和退避的重试，等待期间也能被取消。
//   - breaker.go：熔断器，基于 gobreaker 库，状态变化时写日志。
//   - resilience_test.go：测试限流、退避时间、取消，以及熔断器从打开到恢复的全过程。
//
// 阅读顺序：http.go → retry.go → breaker.go。
