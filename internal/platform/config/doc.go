// Package config 负责读取环境变量，并在程序启动时检查它们是否合法。
//
// 为什么需要它：服务的配置（数据库地址、端口、超时等）都通过环境变量传进来。
// 某个值写错了，比如超时写成 "5"（少了单位），最好在程序启动时就报错退出，
// 而不是等第一个请求进来才出问题。本包就做这件事：读取一个变量，检查格式和范围，
// 不合法就返回一条说清楚“哪个变量、应该是什么”的错误。
//
// 用法：各服务的 app 包在启动时调用 New 得到一个 Reader，再用 String、Int、
// Duration、Bool 逐项读取。每一项都可以给默认值和允许的范围。
//
// 本包只负责“读”和“检查”。配置项叫什么名字、默认值是多少，由各个 app 自己决定。
//
// 文件清单：
//   - doc.go：本说明。
//   - config.go：Reader 和四个读取方法。
//   - config_test.go：用假的环境变量，测试各种正确和错误的输入。
//
// 阅读顺序：先读 config.go 的 String，它区分了“没设置”和“设成空值”两种情况；
// 再看 Int、Duration、Bool 怎样在它的基础上增加格式和范围检查。
