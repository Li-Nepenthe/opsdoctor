// Package app 把医生各部分按启动顺序连接起来。
//
// 接收告警之前，需要先有数据库和账号。启动成功之后，还需要在关闭进程时等待
// 正在保存的通知。这个包负责这些先后关系；具体怎么查指标、怎么去重，仍交给
// 对应的包。阶段 5 没有诊断执行循环，任务创建后保持 pending。
//
// 文件清单：
//   - doc.go：本包的使用背景、边界和阅读顺序。
//   - app.go：按顺序准备医生自己的数据库、接入系统和 HTTP 服务。
//   - cli.go：实现 doctorctl 的三个命令，通过 HTTP 使用正在运行的医生。
//   - cli_test.go：验证命令行始终把工具参数交给同一个医生接口。
//   - config.go：在医生开放端口前检查必填配置和初始登录账号。
//
// 阅读顺序：loadConfig → Run → serve。
