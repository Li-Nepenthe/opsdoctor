// Package app 负责医生服务和 doctorctl 的装配。服务先校验配置与凭据、迁移医生自己的库，再加载各系统、准备账号并启动调度。只有这些操作成功后才监听 HTTP，告警因此可以先持久化再确认。
// 从 Run 读到 assembleAgent，再看 serve 如何给已接收的请求留出停机时间。退出时先停调度，再关闭各系统连接和医生数据库。
//
//   - app.go：按依赖顺序启动服务，处理时钟采样与停机。
//   - config.go：校验服务监听地址、医生数据库与初始登录账号。
//   - agent_config.go：读取模型和调度配置，收集需要脱敏的凭据值。
//   - agent_wiring.go：绑定仓储、模型、调度器与已经提交的步骤事件。
//   - comparison.go：显式启用配对评测时创建独立的模型配置和费用账户。
//   - evaluation.go：按任务记录限定证据时间和可用工具。
//   - metrics.go：记录诊断状态、工具耗时、模型用量和费用，限制指标标签的取值。
//   - cli.go：将 doctorctl 的请求发往医生服务，由同一注册表处理。
