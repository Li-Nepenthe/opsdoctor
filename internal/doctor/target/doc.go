// Package target 把“要诊断哪套系统”变成启动时就确定的连接与工具。
//
// 如果两个系统共用账号，参数检查再严也不能证明数据属于谁。这个包先检查配置名、
// 账号变量名和账号身份，再分别创建连接。调用工具时已经选好了 System，工具自身
// 没有“切换系统”的参数。缺少某个数据源就少提供一组工具，不拿其他系统的数据补。
//
// 文件清单：
//   - profile.go：读取架构组件表，并列出不可用的数据源。
//   - doc.go：本包的使用背景、边界和阅读顺序。
//   - catalog.go：为每个系统分别创建数据源和工具注册表。
//   - catalog_test.go：证明两个系统的工具和告警令牌不会串用。
//   - config.go：读取一个目录里的全部系统配置，并检查系统之间有没有共用凭据。
//
// 阅读顺序：Config → readConfigs → Load → build → System。
