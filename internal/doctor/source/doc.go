// Package source 约定医生查证据时需要的能力。
//
// 医生需要回答“慢在哪一步”“数据库在等什么”，但这些问题不能和某个产品的
// 返回格式绑在一起。这里先用 Go 接口描述问题，各子包再把问题翻译成对应后端的查询。
// 工具依赖这些接口，所以单元测试可以交给它一份假的证据，不必启动整套 Docker。
//
// 本包不含任意 SQL、任意 URL 或命令执行入口。系统地址与账号在组装数据源时确定，
// 后续工具参数不能换一个系统。返回的日志和说明文字也只是数据，不是下一步指令。
//
// 文件清单：
//   - doc.go：本包的使用背景、边界和阅读顺序。
//   - select.go：限制执行计划工具接受的 SELECT 文本。
//   - select_test.go：验证执行计划工具接受的是单条简单 SELECT，而不是任意 SQL。
//   - source.go：约定医生能从外部系统读取哪些证据。
//
// 阅读顺序：先读 source.go 的接口，再按需要进入对应适配器子包。
package source
