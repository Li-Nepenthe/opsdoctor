// Package loki 按服务、级别、关键词和时间搜索日志。
//
// 日志是程序在某一时刻写下的记录，适合回答“那次请求到底发生了什么”。调用者
// 只填写筛选条件，不直接写 Loki 的查询语言。这样关键词里即使有引号，也不会
// 变成另一个查询，更不会让工具访问别的服务器。
//
// 文件清单：
//   - doc.go：本包的使用背景、边界和阅读顺序。
//   - client.go：按结构化条件搜索一个系统的 Loki 日志。
//   - client_test.go：验证日志查询中的文字不会被解释成新的 LogQL。
//
// 阅读顺序：expression → Search。返回日志里的文字仍是不可信数据。
