// Package pprof 让医生查看某个服务的 goroutine 都停在哪里。
//
// 数量上涨只能说明任务越来越多。要继续区分“忙于处理请求”和“停在一处走不动”，
// 还需要调用栈，也就是任务一路调用了哪些函数。Go 的管理端口能把相同调用栈合并，
// 本包再去掉会变化的内存地址，按数量从多到少整理。
//
// 文件清单：
//   - doc.go：本包的使用背景、边界和阅读顺序。
//   - client.go：读取配置中某个服务的 goroutine 文本，并按堆栈合并数量。
//   - client_test.go：验证只查已配置的服务，并把相同函数栈的数量合并。
//
// 阅读顺序：Goroutines → parse。这里没有 CPU profile 采集或其他管理操作。
