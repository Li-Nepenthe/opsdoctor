// Package httpbackend 负责医生向监控后端发出的只读 HTTP 请求。
//
// 一个固定的地址并不自动意味着安全：后端可能把请求重定向到别的主机，或者返回
// 很大的正文。这里统一拒绝跳转，并限制等待时间和读取量。具体查询什么仍由各个
// 适配器决定，本包不会接收来自工具参数的 URL。
//
// 文件清单：
//   - doc.go：本包的使用背景、边界和阅读顺序。
//   - client.go：为只读 HTTP 数据源固定地址、等待时间和响应大小。
//   - client_test.go：验证监控 HTTP 请求不会逃到其他地址，也不会无限读取。
//
// 阅读顺序：New → Bytes → Get。后端返回错误时，只输出状态或分类，不回显正文。
package httpbackend
