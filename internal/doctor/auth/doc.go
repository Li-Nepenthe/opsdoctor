// Package auth 包含医生系统登录要用的规则：签发和校验登录令牌（JWT），以及密码的摘要和校验。
//
// 现状：这些代码从旧项目 ai-backend 迁移过来，目前还没有接到任何 HTTP 接口，
// 等阶段 5 做医生服务时，登录接口才会调用它。先把规则单独放在这里，是为了让
// “密码怎么校验、令牌怎么签发”和“HTTP 请求怎么解析”分开，各自都好测试。
//
// 主要功能：
//   - Tokens：签发（Issue）和解析（Parse）JWT。解析时检查签名算法、签发方、受众、有效期和用户标识，
//     任何一项不对都拒绝。
//   - HashPassword、VerifyPassword：用 bcrypt 计算密码摘要、校验密码。bcrypt 是单向的，
//     只能验证“密码对不对”，不能把摘要还原成密码。
//   - NormalizeEmail：去掉首尾空格并转成小写，同时拒绝格式不对的邮箱。
//
// 本包不查数据库，也不处理 HTTP，这些留给以后的医生服务。
//
// 文件清单：
//   - doc.go：本说明。
//   - auth.go：上面的全部规则。
//   - auth_test.go：测试边界输入，以及各种伪造的令牌（换签名算法、改签发方、过期、篡改内容）是否都被拒绝。
//
// 阅读顺序：先读 auth.go 的 Error 和 Tokens，再按 NewTokens → Issue → Parse 的顺序读，最后看密码和邮箱。
