// Package agent 让模型根据告警提出查询，再用保存的证据提交诊断报告。
// 每次诊断独立累计时间、轮数、工具调用、token 和费用。只读查询可并行，涉及写操作时将申请交给独立的审批接口。
// 业务数据库、HTTP 和目标系统的实现由调用方装配。
//
// 先从 loop.go 的 Run 看查证和整理报告怎样分配时间，再读 calls.go 看工具请求如何变成可引用的步骤。
//
//   - loop.go：调用模型，记录用量，在预算内推进查证和报告。
//   - model.go：约定诊断输入、工具和审批权限，以及审计步骤的编号。
//   - prompt.go：拼接提示与架构资料的固定前缀，附上本系统的工具菜单。
//   - input.go：为最初告警分配证据编号，限定哪些步骤能供只用初始输入的诊断引用。
//   - calls.go：执行只读查询，处理审批和报告请求，再按调用 ID 拼回结果。
//   - budget.go：估算单次请求的上下文，并判断整次诊断还剩多少预算。
//   - replay.go：从已保存的模型请求和工具结果续接中断的诊断。
//   - report.go：声明模型应交的报告格式，核对证据来自本次诊断。
//   - schema.go：为每种组件表缓存可复用的报告校验规则。
