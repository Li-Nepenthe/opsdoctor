// Package llm 约定医生怎样和模型交换消息，以及怎样记录这次交换的费用。
//
// 模型不会直接运行 Go 函数。它返回工具名和一段 JSON 参数，agent 执行后再把结果
// 放进下一次请求。本包保存这套对话格式，openai 子包发送 HTTP，mock 子包按脚本回答。
//
// 所有即将发出的文字先经过 Redactor。费用账本在发送前预留最坏情况的额度，
// 收到用量后再结算。网络中断时无法确认实际扣费，预留额继续保留，避免重试偷偷越过上限。
// 本包不读取告警、不调工具，也不决定诊断结论。
//
// 文件清单：
//   - lease.go：在执行上下文里携带租约编号，过期执行者不能继续记账。
//   - doc.go：对话协议、脱敏与记账的阅读入口。
//   - model.go：消息、工具请求、模型响应和客户端接口。
//   - cost.go：整数费用计算和持久化账本接口。
//   - redact.go：统一清理密钥和令牌，并保持 JSON 可解析。
//   - boundary_test.go：验证金额舍入和秘密信息的清理。
//
// 阅读顺序：model.go → redact.go → cost.go → openai/client.go。
package llm
