// Package mcpserver 让外部编辑器也能使用医生的只读工具。
//
// MCP 是客户端与工具服务交流的一套协议。本包只负责把它翻译成已有注册表的调用，
// 不再写一份数据库查询。每个入口在创建时绑定一个系统，令牌也只属于这个系统。
// 客户端不能在参数里换系统，更不能通过这个入口提交写操作。
//
// 文件清单：
//   - server_test.go：用官方客户端验证工具只读、系统隔离和每次调用审计。
//   - doc.go：使用背景、边界和阅读顺序。
//   - server.go：用官方 SDK 建立只读入口，每个请求检查独立令牌。
//   - audit.go：工具调用前后保存审计，参数只保存脱敏后的摘要。
//
// 阅读顺序：New → authorize → auditCalls。真正的校验、十秒时限和截断仍在 tools 包。
