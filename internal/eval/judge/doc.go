// 本文件：说明评委与被评测医生的职责区别。
//
// 医生只能看到症状，评委还会看到标准答案。两者必须是不同的调用路径，否则
// 就变成把答案交给医生再让它答题。评委没有任何业务工具，只能提交一份评分。
//
// 主要内容与文件清单：
//   - doc.go：本包要解决的问题和阅读顺序。
//   - mock.go：默认不花钱的固定评分脚本，结果明确标为 Mock。
//   - grade.go：组织评委输入、调用模型、检查评分引用。
//   - protocol.go：显式列出待评编号，并生成限定这些编号的工具 Schema。
//   - protocol_test.go：验证规则项被移出待评清单、原编号保持、完整请求能编码。
//   - grade_test.go：用 Mock 检查假引用、重复项目和工具注入。
//   - rubric.md：嵌入程序的通用评分标准，冻结时记录版本与内容哈希。
//
// 阅读建议：先读 rubric.md，再看 Check；模型返回 JSON 不代表里面的引用可信。
