// Package report 把已经保存的诊断整理成表格，不负责替模型补结论。
//
// 没有报告、预算用尽和中断都需要保留。模型实际返回的名字也要保留，不能把中途
// 换模型的结果算到某一个模型名下。人民币和美元分别显示，不能加成一个总费用。
//
// 文件清单：
//   - calibration.go：分层抽取并生成空白盲评表，只比较明确提供的人类评分。
//   - calibration_test.go：验证抽样覆盖、原文安全展示和缺少人工分数时拒绝计算。
//   - statistics.go：分场景、组和模型列出均值、范围与排除项，保留全部费用。
//   - statistics_test.go：验证可靠性与混合模型只退出质量统计，费用仍保留。
//   - summary.go：提取报告、用量、模型变化和主动或预算收尾的标志。
//   - markdown.go：把原始结果导出为 Markdown 表格，缺失数据明确留空。
//   - summary_test.go：验证精确比对、模型变更排除，以及失败和未完成结果保留。
//   - doc.go：说明结果展示的边界和阅读顺序。
//
// 阅读顺序：Summarize → Markdown。
