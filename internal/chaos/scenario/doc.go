// Package scenario 读取“这次实验准备怎样做”的说明文件。
//
// 如果实验只靠手工操作，很容易漏掉恢复步骤，也很难让另一个人重复同样的过程。
// 本包把动作顺序、观察条件和恢复步骤一起读进来，先检查完整性，再交给执行器。
// YAML 是一种适合手写配置的文本格式，缩进表达层级。文件里的 action 是固定动作名，
// 不是可以随便执行的命令；表名、服务名和可改的环境变量都有白名单。
//
// 每个文件还保存调查参考答案。它只给宿主机实验工具和后来的评测器使用，
// 不会送进商品、订单、库存或医生的运行环境。
//
// 文件清单：
//   - component_test.go：从验收侧检查标准答案使用了架构组件表中的标识。
//   - doc.go：本说明。
//   - model.go：场景、动作、症状和参考答案的数据结构。
//   - load.go：读取十一个已授权场景，拒绝缺字段和未知字段。
//   - validate.go：限制动作可以改哪些资源、参数允许多大。
//   - load_test.go：检查真实场景文件和错误输入。
//
// 阅读顺序：先打开一个 eval/scenarios 下的文件，再对照 model.go，最后看校验。
package scenario
