// Package verify 回答两个问题：问题真的出现了吗，现在真的恢复了吗？
//
// “Docker 命令执行成功”只能证明发出了操作，不能证明用户已经受到影响。
// 本包查询 Prometheus 保存的真实指标，还检查是否有对应的告警已经触发。
// 比如网络变慢的场景，要看到库存调用耗时变化，不能只看到服务刚刚重启。
//
// 恢复也不能只看一瞬间。健康检查要求有真实流量、延迟正常、消费追平、依赖可用，
// 并且没有正在触发的告警。所有条件要连续成立一分钟，任何一个坏样本都会重新计时。
// 没有数据或监控查询失败不会被当作健康。
//
// 文件清单：
//   - repairs.go：检查残留索引和运行时连接池修改。
//   - repairs_test.go：验证发现改动或采集缺失时阻止下一场实验。
//   - doc.go：本说明。
//   - baseline.go：检查压测器实际使用的商品数与工作者数，防止重建改变实验条件。
//   - baseline_test.go：验证参数不匹配和控制接口缺字段时立即失败。
//   - prometheus.go：读取即时查询和告警，检查返回格式。
//   - wait.go：轮询症状，连续观察健康，并返回实际等待时间。
//   - verify_test.go：检查空数据、NaN、pending 告警与中途变坏的样本。
//
// 阅读顺序：wait.go 的 Healthy → healthyQueries → prometheus.go 的 Query。
