// Package action 负责真正改变实验环境。
//
// 只说“数据库很慢”不能帮助学习排障。这里会真的删除一个索引、限制可用连接，
// 或让网络数据晚一点到达。业务服务继续运行原来的业务流程，症状由这些原因自然产生。
//
// 外部操作可能已经成功，却因为连接断开而没有返回确认。因此执行失败后不能直接重做实验。
// app 会保存恢复记录，再让本包把网络、配置、镜像和流量恢复到原来的状态。
// 数据库结构使用独立账号，商品缓存操作只处理 product: 前缀，不删除订单幂等记录。
//
// 文件清单：
//   - doc.go：本说明。
//   - runner.go：分派动作，通过参数数组运行 Docker 命令。
//   - deploy.go：保存发布前的公开配置，发布新容器，并按原镜像内容恢复。
//   - http.go：调用网络代理和压测工具的本机控制接口。
//   - storage.go：执行固定索引变更，删除商品缓存或统一到期时间。
//   - runner_test.go：用假命令和本地 HTTP 服务检查动作与恢复。
//
// 阅读顺序：runner.go → 一个具体动作文件 → deploy.go 的恢复过程。
