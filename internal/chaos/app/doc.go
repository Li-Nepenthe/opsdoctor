// Package app 把一次实验从头到尾组织起来。
//
// 一个场景有很多可能中断的地方：改配置时容器启动失败、等待告警时按了 Ctrl+C，
// 或者网络已经变慢，恢复命令却没有得到回复。本包负责保证这些路径都有恢复依据。
//
// 开始修改之前，先把场景和原配置写到宿主机文件。文件独占创建，已有实验没有恢复时，
// 第二个实验不能覆盖它。恢复成功才删除文件；失败则留下它，供 restore-all 再试。
// selftest 按顺序跑每个场景，并把失败行也打印出来。它不会自动补库存或改答案。
//
// 文件清单：
//   - doc.go：本说明。
//   - app.go：解析命令、实验参数，装配真正的执行器和监控客户端。
//   - engine.go：修改前保存记录，按记录恢复。
//   - selftest.go：执行健康、注入、观察、恢复、恢复健康，输出结果表。
//   - engine_test.go：用假的执行器检查取消、部分恢复失败和并发实验保护。
//
// 阅读顺序：app.go 的 Run → selftest.go 的 Trial → engine.go 的 Inject 和 Restore。
