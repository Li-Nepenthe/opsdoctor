// Package loadgen 向订单服务发送受限的 HTTP 流量，使实验能在相同的请求组合下观察业务和故障。
// 它只经过订单服务的公开接口。先读 generator.go 看任务如何分派，再读 client.go 和 stats.go 看一次尝试如何计数。
//
// 调度循环按目标速率生成任务，默认 64 个工作者负责发送。没有空闲工作者时计入 dropped，
// 不继续排队。普通流量约七成查商品、两成下单、一成查订单列表，商品按 Zipf 分布选取。
// 一笔下单如果超时，可以用同一个幂等键再试一次。
//
// 控制端口默认 6070，可以调整普通请求的速率和热点商品，也可以查看当前统计。
// 一批商品查询复用同一组工作者，批次请求数不能超过工作者上限，相邻两批不能重叠。
// 每十秒输出的实际 QPS、错误率和延迟都根据完成的尝试计算，未发出的任务单独列出。
//
//   - config.go：读取环境变量和命令行参数，校验请求目标和资源上限。
//   - app.go：先监听控制端口，再启动调度，退出前等待在途请求结束并输出最终统计。
//   - generator.go：按速率和热点设置生成任务，并分配给固定数量的工作者。
//   - client.go：发送 HTTP 请求，只在下单超时时沿用同一幂等键重试一次。
//   - stats.go：分别累计窗口与全程的完成数、错误数、未发出数和耗时分布。
//   - control.go：提供健康检查、流量设置与统计查询的 HTTP 入口。
//   - burst.go：使用同一组工作者同时查询一种商品，记录当前批次的进度。
