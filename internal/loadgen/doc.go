// Package loadgen 是压测工具：按设定的速率持续给订单服务发送真实的 HTTP 请求。
//
// 为什么需要它：故障要在有流量的时候才看得出来。比如数据库变慢，只有持续有请求，
// 指标和告警才会有反应。
//
// 发什么请求：每个请求随机选一种，长期来看比例约为 70% 查商品、20% 下单、10% 查订单列表。
// 商品编号不是均匀随机的，而是按 Zipf 分布：少数商品特别热门，大部分商品很少被访问，更接近真实的电商。
//
// 怎么发：一个调度循环按目标速率生成任务，固定数量的工作者（默认 64 个）负责实际发送。
// 工作者都忙不过来时，这个任务就被丢弃，并记入 dropped。这样压测工具自己不会因为
// 无限创建 goroutine、无限排队而失控，你也能从 dropped 看出“目标速率其实没发出去”。
//
// 下单请求超时时，会用同一个幂等键重试一次，模拟真实客户端的行为。
//
// 控制接口（端口 6070）：可以随时调整速率、指定一个热点商品，也可以查看统计。
// POST /burst 可以让一批工作者同时查询同一件商品，模拟秒杀开始时一起打开详情页的用户。
// 它只发商品查询。批次大小不能超过固定工作者数，上一批没结束时也不能叠加下一批。
// 统计每 10 秒打印一次，只根据实际完成的请求计算：实际速率、错误率、P50、P99、dropped。
//
// 本包只通过 HTTP 访问订单服务，不直接改数据库。
//
// 文件清单：
//   - doc.go：本说明。
//   - config.go：读取环境变量和命令行参数。
//   - generator.go：调度：决定发什么请求、发给哪个商品、什么时候发。
//   - client.go：实际发送 HTTP 请求，以及下单超时后的重试。
//   - stats.go：统计完成数、错误数和耗时分布。
//   - control.go：控制接口和健康检查。
//   - burst.go：复用固定工作者，发送一批有明确并发上限的商品查询。
//   - burst_test.go：检查突发只查询商品，批次不能叠加，取消后没有工作者卡住。
//   - app.go：启动、定期打印统计、停止时等正在发送的请求结束。
//   - loadgen_test.go：测试请求比例、热点切换、重试时用的是同一个幂等键，以及统计结果是否正确。
//
// 阅读顺序：generator.go → client.go → stats.go。
