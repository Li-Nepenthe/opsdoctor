// Package ops 给已经获批的操作提供一个很窄的业务侧入口。
//
// 医生不能拿业务数据库账号来改配置。它只能带运维令牌请求调整当前进程的连接池，
// 或预热明确列出的商品。这里再检查一次范围，医生端的校验不能替代服务端的保护。
// 监听端口不映射到宿主机，普通业务路由也不会注册这些接口。
//
// 文件清单：
//   - doc.go：运维入口的权限与阅读顺序。
//   - handler.go：令牌、请求格式、连接池条件更新与商品预热。
//   - handler_test.go：验证未授权请求、越界参数和重复操作。
//
// 阅读顺序：New → ServeHTTP → pool → warm。池的修改只影响内存，重启会恢复配置。
