// Package inventoryclient 是订单服务调用库存服务的客户端，在 gRPC 调用外面加了一层保护。
//
// 三个方法，保护方式不一样：
//   - GetStock（查库存）：可以重试。查询不会改数据，重复执行没有副作用。最多试 3 次，
//     每次失败后等一会儿再试，等待时间逐次加倍，并加一点随机量（指数退避加抖动）。
//   - Deduct（扣库存）、Release（归还库存）：只调用一次，绝不自动重试。它们会改数据，
//     如果第一次其实已经成功、只是响应丢了，重试就会扣两次、还两次。
//
// 每次调用（包括重试）共用同一个时限，默认 800 毫秒，重试不会让总耗时越拖越长。
//
// 熔断：查询和扣减各有一个熔断器，各自计数。库存服务持续出错时（默认是 10 秒内至少 10 次调用、
// 其中一半或以上失败），熔断器“打开”，之后的调用直接失败，不再去等库存服务；
// 5 秒后放一个请求试探，成功了就恢复正常。
//
// 本包还把 gRPC 的错误码翻译成订单服务认识的几类错误，订单代码就不用到处判断 gRPC 状态码。
//
// gRPC 连接由 app（orderservice）创建和关闭，本包只是借用它。
//
// 文件清单：
//   - doc.go：本说明。
//   - inventory_client.go：三个方法，以及超时、重试、熔断和错误翻译。
//   - metrics.go：记录熔断器状态和实际重试次数，供监控使用（阶段 3 加入）。
//   - inventory_client_test.go：用假的 gRPC 客户端测试调用次数和错误分类，比如扣减从不重试。
//
// 阅读顺序：先读 GetStock，再对比 Deduct 和 Release 为什么不重试。
