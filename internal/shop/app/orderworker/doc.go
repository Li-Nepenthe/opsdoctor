// Package orderworker 负责把订单消息消费者（order-worker）组装起来并运行。
//
// order-worker 做的事很简单：不停地从 Kafka 读取“订单已创建”消息，交给 sales 包去加销量。
// 它还开了一个管理端口 6063，提供健康检查和指标。
//
// 退出时要注意一点：收到退出信号后，先停止读取新消息；手上正在处理的那一条，
// 给它最多 10 秒做完（写数据库、提交位点）；消费循环结束以后，才关闭 Kafka 连接和数据库连接池。
// 如果直接关掉，正在处理的消息可能写了一半。
//
// 消费的具体顺序在 events 包，销量 SQL 在 sales 包，本包只负责把它们接起来。
//
// 文件清单：
//   - doc.go：本说明。
//   - app.go：Run 读取配置、创建连接、启动消费循环和管理端口；serve 处理退出顺序。
//
// 阅读顺序：先看 Run 创建了哪些资源，再看 serve 为什么要等消费循环结束才关闭连接。
