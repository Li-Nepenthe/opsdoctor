// Package sales 负责商品销量：处理“订单已创建”消息，给对应商品加上卖出的件数。
//
// 难点：同一条消息可能来不止一次。Kafka 只保证消息“至少送到一次”，比如 order-worker
// 处理完一条消息、还没来得及提交位点就崩溃了，重启后这条消息会再来一次。
// 如果每次都加销量，同一笔订单就被算了两次。
//
// 做法：每处理一条消息，在同一个数据库事务里做两件事：
//  1. 往 processed_events 表插入这笔订单的 ID。这张表以订单 ID 为主键，
//     同一笔订单第二次插入会因为主键冲突而失败，说明它已经处理过了，直接跳过。
//  2. 插入成功，才给 product_sales 表里对应商品的销量加上件数。
//
// 两件事在同一个事务里，要么都成功，要么都不生效，不会出现“记了已处理，但销量没加上”的情况。
//
// 谁调用它：order-worker 处理每条消息时调用；shopctl check 调用 Check，核对“订单总件数”
// 和“销量总件数”是否相等。
//
// 本包不负责 Kafka 的位点提交，也不负责补发丢失的消息。
//
// 文件清单：
//   - doc.go：本说明。
//   - model.go：核对结果的类型。
//   - service.go：检查消息内容，再交给 repository。
//   - repository.go：上面两步的 SQL 和事务，以及核对用的查询。
//   - repository_integration_test.go：连真实 MySQL，20 条相同消息同时处理，确认销量只加一次；以及出错时事务整体回滚。
//
// 阅读顺序：先读 repository.go 的两条写入 SQL，再想一想它们为什么必须放在同一个事务里。
