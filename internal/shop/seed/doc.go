// Package seed 负责造测试数据：50 万个商品及其库存，以及 200 万条历史订单。
//
// 为什么需要它：故障实验需要真实的数据规模。比如删掉一个索引后，查询要扫描几十万行才会明显变慢；
// 只有几十行数据，就看不出区别。
//
// 怎么造：按商品编号分批，每批 1000 个商品。每批在一个事务里同时写五张表：商品、库存、
// 订单（每个商品 4 单）、销量，以及“已处理消息”记录。一批要么全部写入，要么全部不写。
// 中途失败了，重新运行会从已经写好的地方接着造。
//
// 两条规则：
//   - 已经有完整数据时直接跳过，不会重置。所以你扣过的库存，重新运行 seed 也不会被改回去。
//   - 造数时要独占数据库：不要同时有下单流量，也不要同时运行两个 seed。
//
// 为什么还要写销量和“已处理消息”：这些历史订单没有经过真正的下单流程，也没有发过消息。
// 直接写好对应的销量和处理记录，后面的一致性检查（shopctl check）才不会把它们当成“漏统计”。
//
// 谁调用它：shopctl seed 命令。加 --small 只造 100 个商品、400 条订单，用于测试。
//
// 文件清单：
//   - doc.go：本说明。
//   - seed.go：Run，决定造多少、从哪里接着造、每批的范围。
//   - repository.go：检查已有数据，生成每批五张表的数据，并在一个事务里写入。
//   - seed_test.go：不连数据库，检查生成的行数、编号和 SQL 占位符。
//   - seed_integration_test.go：连真实 MySQL，测试接着造、跳过，以及失败时整批回滚。
//
// 阅读顺序：seed.go → repository.go → seed_test.go → seed_integration_test.go。
