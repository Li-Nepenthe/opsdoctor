// 本文件：证明三层说明的机器规则能发现缺失，并生成可点击的文件地图。
//
// 这些样例故意把格式写错，所以直接调用原始 fixture，不使用会补齐文件说明的 documentedFixture。
// 先读 TestFileDescriptions 的反例，再看 TestPackageInventory 和 TestMapMode 如何防止清单漏项与链接失效。
//
// 主要内容：
//   - TestFileDescriptions：区分真正的文件导航、贴在 package 上的包文档，以及只有空标题的占位注释。
//   - TestPackageInventory：验证完整文件名匹配。测试文件与生成物不强制列出，但仍可出现在人工说明中。
//   - TestMapMode：核对所有文件都进入地图、相对链接能解析、生成物有标记，并拒绝相互冲突的输出模式。

package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestFileDescriptions 区分真正的文件导航、贴在 package 上的包文档，以及只有空标题的占位注释。
func TestFileDescriptions(t *testing.T) {
	for _, testcase := range []struct {
		name   string // name 描述这份文件说明哪里合格或不合格。
		prefix string // prefix 是放在 package 之前的全部内容。
		valid  bool   // valid 为真时不应产生文件说明错误。
	}{
		{"缺少说明", "", false},                                 // 不能因为函数都有注释就省略文件层。
		{"错误前缀", "// 文件负责查询。\n\n", false},                   // 固定前缀让工具能可靠收集说明。
		{"贴着包名", "// 本文件：查询。\n", false},                     // 没空行会被 Go 解释为包文档。
		{"空标题", "// 本文件：\n\n", false},                       // 只有格式、没有用途不算说明。
		{"没有从首行开始", "\n// 本文件：查询。\n\n", false},              // 打开文件第一行就要看到职责。
		{"完整说明", "// 本文件：查询。\n// 先读 Get，再看错误分类。\n\n", true}, // 多行讲解和一个空行是合法格式。
	} {
		t.Run(testcase.name, func(t *testing.T) {
			root := fixture(t, map[string]string{
				"doc.go":   "// Package demo 是样例；doc.go、query.go 分别说明目录和查询。\npackage demo\n",
				"query.go": testcase.prefix + "package demo\n",
			})
			result, err := scan([]string{root})
			if err != nil {
				t.Fatal(err)
			}
			problems := strings.Join(result.problems, "\n")
			if strings.Contains(problems, "文件说明") == testcase.valid {
				t.Fatalf("文件说明判断不符：%s", problems)
			}
		})
	}
}

// TestPackageInventory 验证完整文件名匹配。测试文件与生成物不强制列出，但仍可出现在人工说明中。
func TestPackageInventory(t *testing.T) {
	for _, testcase := range []struct {
		name      string // name 描述包清单中的引用形式。
		mentioned string // mentioned 模拟 doc.go 写下的文件名。
		valid     bool   // valid 表示是否真正覆盖 query.go。
	}{
		{"漏掉文件", "", false},                 // 新增文件忘记更新目录介绍必须失败。
		{"引用准确", "query.go", true},          // 文件名直接写在说明中即可。
		{"Markdown 包裹", "`query.go`", true}, // 常见排版不能导致误报。
		{"备份文件不能顶替", "query.go.bak", false}, // 子串搜索会错误放过这一项。
		{"其他同名后缀", "old_query.go", false},   // 另一个文件也不能冒充。
	} {
		t.Run(testcase.name, func(t *testing.T) {
			root := fixture(t, map[string]string{
				"doc.go":        "// Package demo 负责样例。\n// doc.go；" + testcase.mentioned + "。\npackage demo\n",
				"query.go":      "// 本文件：查询样例。\n\npackage demo\n",
				"query_test.go": "// 本文件：测试样例。\n\npackage demo_test\n",
				"generated.go":  "// Code generated by test. DO NOT EDIT.\npackage demo\n",
			})
			result, err := scan([]string{root})
			if err != nil || (len(result.problems) == 0) != testcase.valid {
				t.Fatalf("包内清单：%v %v", result.problems, err)
			}
		})
	}
}

// TestMapMode 核对所有文件都进入地图、相对链接能解析、生成物有标记，并拒绝相互冲突的输出模式。
func TestMapMode(t *testing.T) {
	root := fixture(t, map[string]string{
		"demo/doc.go":       "// Package demo 展示地图。\n// doc.go 和 query.go 是包说明与查询。\npackage demo\n",
		"demo/query.go":     "// 本文件：查询样例。第二句话不进入地图。\n\npackage demo\n",
		"demo/generated.go": "// Code generated by test. DO NOT EDIT.\npackage demo\n",
		"cmd/demo/main.go":  "// 演示命令入口。\npackage main\n// main 是入口。\nfunc main() {}\n",
	})
	// 使用独立临时工作目录，让地图中的 ../ 相对于该仓库 docs，而不是指向真实仓库。
	t.Chdir(root)
	var output bytes.Buffer
	if err := run([]string{"-map", "./..."}, &output); err != nil {
		t.Fatal(err)
	}
	if strings.Contains(output.String(), "第二句话") || !strings.Contains(output.String(), "工具生成") {
		t.Fatalf("说明摘要：%s", output.String())
	}
	for _, name := range []string{"demo/doc.go", "demo/query.go", "demo/generated.go", "cmd/demo/main.go"} {
		relative := "../" + name
		if !strings.Contains(output.String(), "]("+relative+")") {
			t.Fatalf("地图遗漏链接 %s", name)
		}
		if _, err := os.Stat(filepath.Join(root, "docs", filepath.FromSlash(relative))); err != nil {
			t.Fatal(err)
		}
	}
	if err := run([]string{"-map", "-list", "./..."}, &bytes.Buffer{}); err == nil {
		t.Fatal("相互冲突的模式未被拒绝")
	}
}
