// TestPackageAndGenerated 验证空 doc.go 不能通过，标准生成文件则不要求手写注释。
func TestPackageAndGenerated(t *testing.T) {
	// 一个样例缺包注释，另一个带标准生成标记。应只留下前者的错误，生成文件也不计入文件数。
	root := documentedFixture(t, map[string]string{"doc.go": "package demo\n", "generated.go": "// Code generated by test. DO NOT EDIT.\npackage demo\nfunc Missing() {}\n"})
	result, err := scan([]string{root})
	if err != nil || len(result.problems) != 1 || !strings.Contains(result.problems[0], "doc.go") {
		t.Fatalf("包检查：%+v %v", result, err)
	}
	if result.files != 1 {
		t.Fatal("生成文件未排除")
	}
}

// TestListAndGroupedComments 检查组注释以及阅读清单保留的第一句说明。
func TestListAndGroupedComments(t *testing.T) {
	source := "package demo\n// Limits 说明一组常量。\nconst (A = 1; B = 2)\n// Item 是样例类型。\ntype Item struct{}\n// Work 说明第一句。第二句。\nfunc (Item) Work() {\n" + strings.Repeat("println(1)\n", 16) + "}\n"
	root := documentedFixture(t, map[string]string{"doc.go": "// Package demo 说明职责。\npackage demo\n", "sample.go": source})
	var output bytes.Buffer
	if err := run([]string{"-list", root}, &output); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(output.String(), "Item.Work") || !strings.Contains(output.String(), "Work 说明第一句") || strings.Contains(output.String(), "第二句") {
		t.Fatalf("清单不正确：%s", output.String())
	}
}

// TestSyntaxErrorAndExit 检查语法错误和违规不会在 CLI 入口被吞掉，确保 CI 能收到失败。
func TestSyntaxErrorAndExit(t *testing.T) {
	// 语法坏掉时不能完成检查，应把解析错误返回给 CLI。
	root := documentedFixture(t, map[string]string{"broken.go": "package demo\nfunc ("})
	if _, err := scan([]string{root}); err == nil {
		t.Fatal("语法错误被忽略")
	}
	// 语法正确但规则不通过也必须返回错误，main 才能据此让 CI 失败。
	root = documentedFixture(t, map[string]string{"bad.go": "package demo\nfunc Missing() {}"})
	if err := run([]string{root}, &bytes.Buffer{}); err == nil {
		t.Fatal("违规没有返回错误")
	}
}

// TestCommandPackageDoc 验证 cmd 单文件入口的包说明例外，不放宽普通包或缺注释入口。
func TestCommandPackageDoc(t *testing.T) {
	for _, testcase := range []struct {
		name   string // name 描述目录规则与包注释的组合。
		path   string // path 相对临时仓库，模拟真正 cmd 结构。
		source string // source 只交给 AST 解析，不编译执行。
		valid  bool   // valid 表示包级说明是否合格。
	}{
		{"cmd 有包注释", "cmd/demo/main.go", "// 演示程序入口。\npackage main\n// main 只作为入口。\nfunc main() {}", true},
		{"cmd 缺包注释", "cmd/demo/main.go", "package main\n// main 只作为入口。\nfunc main() {}", false},
		{"普通包不可冒充入口", "internal/demo/main.go", "// 演示普通包。\npackage main\n// main 是样例。\nfunc main() {}", false},
		{"目录名字仅相似", "mycmd/demo/main.go", "// 演示普通包。\npackage main\n// main 是样例。\nfunc main() {}", false},
	} {
		t.Run(testcase.name, func(t *testing.T) {
			root := documentedFixture(t, map[string]string{testcase.path: testcase.source})
			result, err := scan([]string{root})
			if err != nil || (len(result.problems) == 0) != testcase.valid {
				t.Fatalf("包说明检查：%v %v", result.problems, err)
			}
		})
	}
}
