// Package main 是 commentcheck 工具：自动检查代码有没有按项目规范写说明。
//
// 项目要求说明分三层：目录（README、doc.go）、文件（文件开头的“本文件：”说明）、
// 代码（函数、类型等的注释）。人写代码时难免漏掉，本工具在 CI 里自动检查，
// 发现遗漏就报错，并给出文件名和行号。它检查这几件事：
//   - 每个包都有 doc.go，并且 doc.go 提到了包里的每一个文件；
//   - 每个 .go 文件开头都有“// 本文件：”说明，并且和 package 之间空一行；
//   - 每个函数、类型、包级常量和变量都有注释；
//   - 函数体超过 15 行时，内部至少有一条注释。
//
// 它只能检查“有没有写”，不能判断“写得好不好”，所以仍然需要人来读。
//
// 三种用法：
//   - go run ./tools/commentcheck ./...：执行检查，发现问题时以非 0 退出码结束。
//   - 加 -list：列出所有函数、类型和它们注释的第一句，写阶段汇报书时用。
//   - 加 -map：生成 docs/代码地图.md 里的文件清单表格。
//
// 文件清单：
//   - doc.go：本说明。
//   - main.go：解析命令行参数，决定执行哪种用法。
//   - check.go：解析源码，检查函数、类型等的注释。
//   - files.go：检查文件说明和 doc.go 的文件清单，并生成代码地图。
//   - check_test.go：用故意缺注释的代码，证明 check.go 的规则真能发现问题。
//   - files_test.go：同样用反例证明 files.go 的规则有效，并检查生成的地图链接。
//
// 阅读顺序：main.go → check.go → files.go，最后看两份测试。本工具要用 Go 的语法树（go/ast）
// 分析源码，对初学者偏难，建议放在阶段 0 的最后读。
